//! Relocates a whole clangd index directory from a donor worktree to a target worktree, in parallel.

use std::collections::{BTreeSet, HashSet};
use std::fs;
use std::path::{Path, PathBuf};
use std::time::{Duration, Instant};

use anyhow::{Context, Result, bail};
use rayon::prelude::*;

use super::path_map::PathMap;
use super::shard_relocation::{HashSelfCheckError, UnsupportedVersionError, relocate_shard};
use crate::atomic_write::{WriteOutcome, write_atomically, write_unless_exists};
use crate::format::shard::SUPPORTED_VERSIONS;
use crate::format::string_table::TableCompression;

/// Where clangd keeps a project's shards, relative to the project root (the compilation database's directory).
pub const INDEX_RELATIVE_DIR: &str = ".cache/clangd/index";
const SHARD_EXTENSION: &str = "idx";
const GITIGNORE_NAME: &str = ".gitignore";
/// The `.gitignore` clangd writes into every index directory.
const GITIGNORE_CONTENT: &str = "# This file is autogenerated by clangd.\n*\n";

pub struct IndexRelocationRequest {
    /// Donor `.cache/clangd/index` directory.
    pub donor_dir: PathBuf,
    /// Target `.cache/clangd/index` directory; created when missing.
    pub target_dir: PathBuf,
    pub path_map: PathMap,
    pub compression: TableCompression,
    /// Replace target shards that already exist instead of keeping them (clangd wrote them, so they are fresher).
    pub is_overwrite: bool,
    /// Relocate in memory but write nothing, not even the target directory.
    pub is_dry_run: bool,
    /// Absolute mapped source paths whose shards are not copied (files deleted in the target).
    pub deleted_target_paths: HashSet<PathBuf>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ShardFailure {
    pub donor_shard: PathBuf,
    pub reason: String,
}

#[derive(Clone, Debug)]
pub struct IndexRelocationReport {
    /// Shards written to the target (or that would be, in a dry run).
    pub relocated: usize,
    pub skipped_existing: usize,
    pub skipped_deleted: usize,
    /// Shards of a format version this tool does not support; never relocated.
    pub skipped_unsupported_version: usize,
    /// Shards that could not be read, relocated or written, sorted by donor path.
    pub failures: Vec<ShardFailure>,
    /// String-table entries the path map changed across all relocated, kept and deleted shards.
    pub rewritten_strings: usize,
    pub elapsed: Duration,
}

/// Fails as a whole when the directories are unusable or a supported-version shard fails the path-hash
/// self-check; any other per-shard problem is reported in [`IndexRelocationReport::failures`].
/// On a self-check failure, shards that passed it may already be written; their names are verified.
pub fn relocate_index(request: &IndexRelocationRequest) -> Result<IndexRelocationReport> {
    let started = Instant::now();
    validate_dirs(&request.donor_dir, &request.target_dir)?;
    let donor_shards = list_shards(&request.donor_dir)?;
    if !request.is_dry_run {
        prepare_target_dir(&request.target_dir)?;
    }

    // `collect` keeps the sorted input order, so failures come out sorted by donor path.
    let outcomes = donor_shards.par_iter().map(|donor_shard| relocate_one(donor_shard, request)).collect::<Result<Vec<ShardOutcome>>>()?;
    warn_unsupported_versions(&outcomes);
    Ok(summarize(outcomes, started.elapsed()))
}

/// `rewritten_strings` counts the strings the path map changed in the shard.
enum ShardOutcome {
    Relocated { rewritten_strings: usize },
    SkippedExisting { rewritten_strings: usize },
    SkippedDeleted { rewritten_strings: usize },
    SkippedUnsupportedVersion(u32),
    Failed(ShardFailure),
}

fn validate_dirs(donor_dir: &Path, target_dir: &Path) -> Result<()> {
    let donor = fs::canonicalize(donor_dir).with_context(|| format!("donor index {}", donor_dir.display()))?;
    if !donor.is_dir() {
        bail!("donor index {} is not a directory", donor_dir.display());
    }
    let is_same_dir =
        target_dir.exists() && fs::canonicalize(target_dir).with_context(|| format!("target index {}", target_dir.display()))? == donor;
    if is_same_dir {
        bail!("donor and target index are the same directory: {}", donor.display());
    }
    Ok(())
}

/// Shard paths sorted by name, so outcomes are deterministic.
pub fn list_shards(dir: &Path) -> Result<Vec<PathBuf>> {
    let mut shards = Vec::new();
    for entry in fs::read_dir(dir).with_context(|| format!("listing {}", dir.display()))? {
        let entry = entry.with_context(|| format!("listing {}", dir.display()))?;
        let path = entry.path();
        let is_shard = path.extension().is_some_and(|extension| extension == SHARD_EXTENSION)
            && entry.file_type().with_context(|| format!("inspecting {}", path.display()))?.is_file();
        if is_shard {
            shards.push(path);
        }
    }
    shards.sort();
    Ok(shards)
}

fn prepare_target_dir(target_dir: &Path) -> Result<()> {
    fs::create_dir_all(target_dir).with_context(|| format!("creating {}", target_dir.display()))?;
    let gitignore = target_dir.join(GITIGNORE_NAME);
    write_unless_exists(&gitignore, GITIGNORE_CONTENT.as_bytes())?;
    Ok(())
}

fn relocate_one(donor_shard: &Path, request: &IndexRelocationRequest) -> Result<ShardOutcome> {
    match relocate_donor_shard(donor_shard, request) {
        Ok(outcome) => Ok(outcome),
        Err(error) if error.is::<HashSelfCheckError>() => Err(error),
        Err(error) => Ok(classify_shard_error(donor_shard, &error)),
    }
}

fn classify_shard_error(donor_shard: &Path, error: &anyhow::Error) -> ShardOutcome {
    if let Some(unsupported) = error.downcast_ref::<UnsupportedVersionError>() {
        return ShardOutcome::SkippedUnsupportedVersion(unsupported.version);
    }
    log::debug!("{}: {error:#}", donor_shard.display());
    ShardOutcome::Failed(ShardFailure { donor_shard: donor_shard.to_path_buf(), reason: format!("{error:#}") })
}

fn relocate_donor_shard(donor_shard: &Path, request: &IndexRelocationRequest) -> Result<ShardOutcome> {
    let bytes = fs::read(donor_shard).context("reading shard")?;
    let file_name = donor_shard.file_name().context("shard path has no file name")?;
    let relocated = relocate_shard(file_name, &bytes, &request.path_map, request.compression)?;
    let rewritten_strings = relocated.rewritten_strings;
    if request.deleted_target_paths.contains(&relocated.source_path) {
        return Ok(ShardOutcome::SkippedDeleted { rewritten_strings });
    }

    let target_shard = request.target_dir.join(&relocated.file_name);
    // Fast path only; `write_unless_exists` decides atomically.
    let is_kept = !request.is_overwrite && target_shard.exists();
    if is_kept {
        return Ok(ShardOutcome::SkippedExisting { rewritten_strings });
    }
    if request.is_dry_run {
        return Ok(ShardOutcome::Relocated { rewritten_strings });
    }
    if request.is_overwrite {
        write_atomically(&target_shard, &relocated.bytes, None)?;
        return Ok(ShardOutcome::Relocated { rewritten_strings });
    }
    match write_unless_exists(&target_shard, &relocated.bytes)? {
        WriteOutcome::Written => Ok(ShardOutcome::Relocated { rewritten_strings }),
        WriteOutcome::TargetExists => Ok(ShardOutcome::SkippedExisting { rewritten_strings }),
    }
}

/// One warning per run, not per shard: an old index can hold thousands of orphaned shards.
fn warn_unsupported_versions(outcomes: &[ShardOutcome]) {
    let versions: BTreeSet<u32> = outcomes
        .iter()
        .filter_map(|outcome| if let ShardOutcome::SkippedUnsupportedVersion(version) = outcome { Some(*version) } else { None })
        .collect();
    if versions.is_empty() {
        return;
    }
    log::warn!("skipped shards of unsupported format versions {versions:?}; supported: {SUPPORTED_VERSIONS:?}");
}

fn summarize(outcomes: Vec<ShardOutcome>, elapsed: Duration) -> IndexRelocationReport {
    let mut report = IndexRelocationReport {
        relocated: 0,
        skipped_existing: 0,
        skipped_deleted: 0,
        skipped_unsupported_version: 0,
        failures: Vec::new(),
        rewritten_strings: 0,
        elapsed,
    };
    for outcome in outcomes {
        match outcome {
            ShardOutcome::Relocated { rewritten_strings } => {
                report.relocated += 1;
                report.rewritten_strings += rewritten_strings;
            }
            ShardOutcome::SkippedExisting { rewritten_strings } => {
                report.skipped_existing += 1;
                report.rewritten_strings += rewritten_strings;
            }
            ShardOutcome::SkippedDeleted { rewritten_strings } => {
                report.skipped_deleted += 1;
                report.rewritten_strings += rewritten_strings;
            }
            ShardOutcome::SkippedUnsupportedVersion(_) => report.skipped_unsupported_version += 1,
            ShardOutcome::Failed(failure) => report.failures.push(failure),
        }
    }
    report
}
