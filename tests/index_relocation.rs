#[test]
fn aborts_when_path_hash_self_check_fails() {
    let workspace = workspace();
    fs::write(workspace.donor_dir.join(MISNAMED_SHARD), read_fixture(TU_SHARD)).unwrap();

    let result = relocate_index(&request(&workspace));

    assert!(result.unwrap_err().downcast_ref::<HashSelfCheckError>().is_some());
}

#[test]
fn skips_unsupported_version_shard_before_self_check() {
    let workspace = workspace();
    fs::write(workspace.donor_dir.join(MISNAMED_SHARD), with_version(&read_fixture(TU_SHARD), UNSUPPORTED_VERSION)).unwrap();

    let report = relocate_index(&request(&workspace)).unwrap();

    let expected = Counts { relocated: 3, skipped_existing: 0, skipped_deleted: 0, skipped_unsupported_version: 1, failed: 1 };
    assert_eq!(counts(&report), expected);
}

/// Copies the TU fixture into the donor a second time, as if indexed from `OTHER_ROOT`, and maps both roots
/// onto `TARGET_ROOT`; returns the bytes each copy relocates to.
fn add_colliding_tu_shard(workspace: &Workspace) -> Vec<Vec<u8>> {
    let other_tu =
        relocate_shard(&os(TU_SHARD), &read_fixture(TU_SHARD), &path_map(SAMPLE_ROOT, OTHER_ROOT), TableCompression::Fast).unwrap();
    fs::write(workspace.donor_dir.join(&other_tu.file_name), &other_tu.bytes).unwrap();
    let from_other = relocate_shard(&other_tu.file_name, &other_tu.bytes, &path_map(OTHER_ROOT, TARGET_ROOT), TableCompression::Fast);
    let from_sample = relocate_shard(&os(TU_SHARD), &read_fixture(TU_SHARD), &path_map(SAMPLE_ROOT, TARGET_ROOT), TableCompression::Fast);
    vec![from_sample.unwrap().bytes, from_other.unwrap().bytes]
}

fn colliding_path_map() -> PathMap {
    let mappings = [SAMPLE_ROOT, OTHER_ROOT]
        .map(|old_root| RootMapping { old_root: old_root.as_bytes().to_vec(), new_root: TARGET_ROOT.as_bytes().to_vec() });
    PathMap::new(&mappings).unwrap()
}

#[test]
fn writes_one_whole_shard_when_two_donor_shards_map_to_one_target() {
    for is_overwrite in [false, true] {
        let workspace = workspace();
        let candidates = add_colliding_tu_shard(&workspace);

        let report = relocate_index(&IndexRelocationRequest { path_map: colliding_path_map(), is_overwrite, ..request(&workspace) });

        let expected = if is_overwrite {
            Counts { relocated: 4, skipped_existing: 0, skipped_deleted: 0, skipped_unsupported_version: 0, failed: 1 }
        } else {
            Counts { relocated: 3, skipped_existing: 1, skipped_deleted: 0, skipped_unsupported_version: 0, failed: 1 }
        };
        assert_eq!(counts(&report.unwrap()), expected, "is_overwrite: {is_overwrite}");
        let written = fs::read(workspace.target_dir.join(relocated_name(TU_SHARD))).unwrap();
        assert!(candidates.contains(&written), "is_overwrite: {is_overwrite}");
        assert!(!file_names(&workspace.target_dir).iter().any(|name| name.ends_with(".tmp")));
    }
}

#[test]
fn leaves_no_temp_files_behind() {
    let workspace = workspace();

    relocate_index(&request(&workspace)).unwrap();

    let temp_files: Vec<String> = file_names(&workspace.target_dir).into_iter().filter(|name| name.ends_with(".tmp")).collect();
    assert_eq!(temp_files, Vec::<String>::new());
}
